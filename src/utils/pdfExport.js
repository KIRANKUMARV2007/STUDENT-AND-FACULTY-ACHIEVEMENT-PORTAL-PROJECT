import jsPDF from 'jspdf';
import 'jspdf-autotable';

/**
 * Utility function to export a table to a highly styled, professional PDF
 * @param {Object} options - Configuration options for the PDF export
 * @param {string} options.title - The main title of the report (e.g., 'Pending Approvals')
 * @param {Array<Object>} options.data - The array of objects representing the rows
 * @param {Array<string>} options.headers - The array of string headers
 * @param {Array<string>} options.keys - The object keys that map to the headers
 * @param {string} options.generatedBy - Name of the faculty/admin who generated the report
 * @param {string} [options.orientation='landscape'] - 'landscape' or 'portrait'
 */
export const exportToPDF = ({
  title,
  data,
  headers,
  keys,
  generatedBy = 'Faculty Member',
  orientation = 'landscape'
}) => {
  const doc = new jsPDF(orientation, 'mm', 'a4');
  
  // Dimensions
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const primaryColor = [33, 86, 166]; // Matching the portal's brand blue

  // Prepare Data for AutoTable
  const tableData = data.map(item => 
    keys.map(key => {
      let val = item[key];
      // Format nested or special objects if needed
      if (val === null || val === undefined) return 'N/A';
      return String(val);
    })
  );

  // College Branding & Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text('College Achievement Portal', pageWidth / 2, 20, { align: 'center' });

  doc.setFontSize(14);
  doc.setTextColor(40, 40, 40);
  doc.text(title, pageWidth / 2, 30, { align: 'center' });

  // Divider Line
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.5);
  doc.line(14, 35, pageWidth - 14, 35);

  // Metadata
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 100, 100);
  doc.text(`Generated By: ${generatedBy}`, 14, 45);
  
  const currentDate = new Date().toLocaleDateString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric',
    hour: '2-digit', minute: '2-digit'
  });
  doc.text(`Date: ${currentDate}`, pageWidth - 14, 45, { align: 'right' });

  // Generate Table
  doc.autoTable({
    startY: 52,
    head: [headers],
    body: tableData,
    theme: 'striped',
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      halign: 'center'
    },
    styles: {
      fontSize: 9,
      cellPadding: 4,
      valign: 'middle',
      textColor: [50, 50, 50],
    },
    alternateRowStyles: {
      fillColor: [245, 247, 250]
    },
    margin: { top: 52, right: 14, bottom: 20, left: 14 },
    didDrawPage: function (data) {
      // Footer Pagination
      const pageCount = doc.internal.getNumberOfPages();
      doc.setFontSize(8);
      doc.setTextColor(150, 150, 150);
      doc.text(
        `Page ${data.pageNumber}`,
        pageWidth / 2,
        pageHeight - 10,
        { align: 'center' }
      );
    }
  });

  // Save the PDF
  const filename = `${title.replace(/\s+/g, '_').toLowerCase()}_report.pdf`;
  doc.save(filename);
};
